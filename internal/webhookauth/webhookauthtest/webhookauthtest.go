// Package webhookauthtest is the VerificationScheme conformance suite
// (Stage 10.3 W1a, WH-VENDOR-SCHEME-1; 01-provider-trust-analysis.md §1.2
// SC1-SC13, as conditioned by 04-review-security.md C3/C9/C10/C11 and the
// binding QA plan 04-review-qa.md §4 W1a). Every scheme - the platform MOCK
// schemes and every future real vendor scheme - must pass
// RunSchemeConformance before it may be registered (see
// webhookauth.ConformanceManifest and this package's registry test).
//
// Rules the suite enforces on itself:
//
//   - It tests the RAW scheme, never the platform wrappers
//     (webhookauth.ExtractInbound/VerifyInbound), so a platform-side defence
//     can never mask a broken scheme.
//   - Tampering is generated by the suite (SC2): every byte of the body and
//     of every header the fixture DECLARES as authentication material is
//     flipped, and each such header is truncated and extended. The fixture
//     only declares the header set.
//   - SC7 (timestamp window) is fail-not-skip for every non-synthetic
//     scheme. The MOCK is exempt only because it is synthetic (its bytes
//     are frozen; replay is inert by idempotency) and can never run in
//     production.
//   - A non-synthetic scheme needs at least one vendor known-answer vector
//     (KAV) taken from the vendor's documentation or a recorded sandbox
//     delivery, with provenance, so a bug shared by the fixture's Sign and
//     the scheme's Verify cannot pass.
//   - Each mandatory case is load-bearing: the package's self-test runs one
//     deliberately broken reference scheme per mandatory case and proves
//     that exactly that case, and no other, goes red.
//
// Constant-time comparison cannot be proven black-box; it is enforced by the
// AST rule in internal/webhookauth (constant_time_lint_test.go).
//
// This is a non-_test package so that domain packages' tests can import it;
// it must never be imported by production code.
package webhookauthtest

