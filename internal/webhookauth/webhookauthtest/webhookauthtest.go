// Fixture is what a scheme's owner supplies. Sign must implement the
// vendor's DOCUMENTED algorithm (or replay recorded sandbox fixtures) -
// never an invented one.
type Fixture struct {
	// Scheme under test.
	Scheme webhookauth.VerificationScheme
	// AuthHeaders is every request header the scheme treats as
	// authentication material (signature, key id, timestamp, account id,
	// ...). The suite tampers every byte of each. Order matters only for
	// SC13 (cross-domain header mapping).
	AuthHeaders []string
	// KeyIDHeader names the key-id header. Required (and must be one of
	// AuthHeaders) iff Properties().KeySelection == KeyFromHeader.
	KeyIDHeader string
	// Sign returns the authentication headers for body routed as
	// (tenantID, providerID), signed with cred at time at. It uses
	// cred.KeyID (KeyFromHeader) and cred.BoundAccountID
	// (PerMerchantKeySignedAccount) as the vendor would.
	Sign func(cred webhookauth.Credential, tenantID uuid.UUID, providerID string, body []byte, at time.Time) http.Header
	// NewCredential returns a fresh credential with an independent random
	// secret of at least webhookauth.MinSecretBytes for (tenant, provider,
	// key id).
	NewCredential func(tenantID uuid.UUID, providerID, keyID string) webhookauth.Credential
	// Now is the platform clock for the run; zero means DefaultNow.
	Now time.Time
	// KnownAnswers are vendor known-answer vectors. At least one valid
	// vector is required for a non-synthetic scheme.
	KnownAnswers []KnownAnswer
	// CrossDomain (synthetic MOCK schemes only, SC13) are the other
	// domains' MOCK fixtures; their AuthHeaders must be in the same order
	// (signature, key id) as this fixture's.
	CrossDomain []Fixture
}

// KnownAnswer is one vendor known-answer vector. It must contain no real
// credential: a vendor-published test key, or a sandbox key rotated after
// capture.
type KnownAnswer struct {
	// Provenance is where the vector comes from (document + section, or
	// sandbox capture id and date). Required.
	Provenance string
	Credential webhookauth.Credential
	Inbound    webhookauth.Inbound
	Now        time.Time
	WantValid  bool
}

// DefaultNow is the fixed platform clock used when Fixture.Now is zero.
var DefaultNow = time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)

