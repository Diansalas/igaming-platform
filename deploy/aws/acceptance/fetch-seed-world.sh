#!/usr/bin/env bash
# Turn the Secrets Manager secret written by the runner mode `seed-world` (docs/plans/staging-acceptance-suite-record.md, finding SA-1;
# docs/runbooks/aws-staging-deploy-plan.md 6.4) into the files and variables the acceptance suite consumes (README section 2).
#
#   deploy/aws/acceptance/fetch-seed-world.sh <output-directory>
#
# It reads igaming-staging/seed-world-passwords with the OPERATOR's own AWS credential (aws secretsmanager get-secret-value; the staging
# deployer can read every igaming-staging/* secret), and writes into <output-directory> (created 0700, OUTSIDE the repository):
#   <KEY>.pw       the one-time password                       0600   -> <KEY>_PASSWORD_FILE
#   <KEY>.token    the single-use bootstrap enrolment token    0600   -> <KEY>_BOOTSTRAP_TOKEN_FILE
#   suite.env      NON-secret exports: TENANT, BRAND, <KEY>_EMAIL, the file paths, and <KEY>_TOTP_SECRET_FILE (a path that does not exist yet:
#                  the suite writes the TOTP secret there on first enrolment, README section 3)
# for KEY in TENANT_ADMIN FINANCE1 FINANCE2 COMPLIANCE RISK_MANAGER. No secret is printed, logged or put on a command line (jq writes the values
# straight to the files; the AWS CLI response goes to a 0600 file that is removed). An existing TOTP secret file is never touched.
# Offline use / tests: SEED_WORLD_JSON_FILE=<file> reads the JSON from that file instead of calling AWS.
set -euo pipefail
umask 077

out="${1:-}"
[ -n "$out" ] || { echo "usage: $0 <output-directory>" >&2; exit 2; }
case "$out" in /*) ;; *) echo "the output directory must be an absolute path" >&2; exit 2 ;; esac
out="$(realpath -m "$out")"
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
case "$out/" in "$repo_root"/*) echo "refusing to write credentials inside the repository checkout" >&2; exit 2 ;; esac
command -v jq >/dev/null || { echo "jq is required" >&2; exit 2; }

mkdir -p "$out"
chmod 700 "$out"
raw="$(mktemp "$out/.seed-world.XXXXXX")"
trap 'rm -f "$raw"' EXIT
if [ -n "${SEED_WORLD_JSON_FILE:-}" ]; then
  cp "$SEED_WORLD_JSON_FILE" "$raw"
else
  command -v aws >/dev/null || { echo "the aws CLI is required" >&2; exit 2; }
  aws secretsmanager get-secret-value --region "${AWS_REGION:-eu-central-1}" --secret-id igaming-staging/seed-world-passwords \
    --query SecretString --output text >"$raw"
fi
jq -e '.tenant_slug and .brand_slug and (.actors | type == "object")' "$raw" >/dev/null || { echo "the secret does not look like a seed-world credentials document" >&2; exit 1; }

env_file="$out/suite.env"
tmp_env="$(mktemp "$out/.suite.env.XXXXXX")"
{
  printf '# generated by fetch-seed-world.sh: non-secret variables for the acceptance suite\n'
  printf 'export TENANT=%q\n' "$(jq -r '.tenant_slug' "$raw")"
  printf 'export BRAND=%q\n' "$(jq -r '.brand_slug' "$raw")"
} >"$tmp_env"

count=0
for key in TENANT_ADMIN FINANCE1 FINANCE2 COMPLIANCE RISK_MANAGER; do
  if ! jq -e --arg k "$key" '.actors[$k] | type == "object"' "$raw" >/dev/null; then
    echo "note: ${key} is not in the secret (not created by seed-world, or already provisioned another way)" >&2
    continue
  fi
  jq -j --arg k "$key" '.actors[$k].password // empty' "$raw" >"$out/${key}.pw"
  jq -j --arg k "$key" '.actors[$k].bootstrap_token // empty' "$raw" >"$out/${key}.token"
  chmod 600 "$out/${key}.pw" "$out/${key}.token"
  [ -s "$out/${key}.token" ] || rm -f "$out/${key}.token"
  {
    printf 'export %s_EMAIL=%q\n' "$key" "$(jq -r --arg k "$key" '.actors[$k].email' "$raw")"
    printf 'export %s_PASSWORD_FILE=%q\n' "$key" "$out/${key}.pw"
    [ ! -s "$out/${key}.token" ] || printf 'export %s_BOOTSTRAP_TOKEN_FILE=%q\n' "$key" "$out/${key}.token"
    printf 'export %s_TOTP_SECRET_FILE=%q\n' "$key" "$out/${key}.totp"
  } >>"$tmp_env"
  count=$((count + 1))
done
mv -f "$tmp_env" "$env_file"
chmod 600 "$env_file"
echo "wrote ${count} account(s) (0600 files, values not printed) and ${env_file}; load the variables with: . ${env_file}"
